def display_time(r):
    if r.get('time_format')=='epoch-decimal':
        d=Decimal(r['time']);seconds=int(d);us=int((d-seconds)*1000000)
        return (datetime(1970,1,1,tzinfo=timezone.utc)+timedelta(seconds=seconds,microseconds=us)).isoformat()
    return r.get('time') or 'unknown'

