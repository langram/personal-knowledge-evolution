def readable(t):
 out=[]
 for para in t.split('\n\n'):
  if len(para)<480 or '\n' in para or para.startswith(('#','|','>')):
   out.append(para);continue
  pieces=re.split(r'(?<=[。！？])',para);buf=''
  for part in pieces:
   if len(buf)>230 and len(buf)+len(part)>430:
    out.append(buf);buf=part
   else:buf+=part
  if buf:out.append(buf)
 return '\n\n'.join(out)

