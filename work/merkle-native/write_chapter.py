def build():
    baseline = json.loads((ARCHIVE / 'baseline.json').read_bytes())
    old = OLD.read_bytes()
    assert sha(old) == baseline['sha256']
    marker = '## 人和 AI 怎样共同研究与构造\n'.encode()
    assert old.count(marker) == 1
    at = old.index(marker)
    chapter = '## ' + TITLE + '\n\n'
    for ordinal, item in enumerate(ITEMS):
        item['ordinal'] = ordinal
        item['chapter_span'] = [len(chapter), len(chapter)+len(item['text'])]
        item['document_span'] = [len(old[:at].decode())+x for x in item['chapter_span']]
        chapter += item['text'] + '\n\n'
    data = chapter.encode(); combined = old[:at]+data+old[at:]
    (OUT/'01-chapter.md').write_bytes(data)
    (OUT/'02-new-principles.md').write_bytes(combined)
    write_json(OUT/'passage-manifest.json', {'schema':'mn/passages@1', 'title':TITLE,
        'coordinate':'Unicode code points, half-open', 'sources':{k:v['occurrence'] for k,v in SOURCES.items()}, 'items':ITEMS})
    write_json(OUT/'insertion-manifest.json', {'schema':'mn/insertion@1',
        'baseline_file':baseline['manuscript'], 'baseline_sha256':sha(old), 'insert_at_utf8_byte':at,
        'inserted_bytes':len(data), 'chapter_sha256':sha(data), 'combined_sha256':sha(combined),
        'placement':'after MerkleVM software seed, before human and AI collaborative construction',
        'outside_chapter_byte_preserved':True, 'author_acceptance':'integration requested; specific editorial changes pending review'})
    metrics={'chapter_cjk':len(re.findall('[\u3400-\u9fff]',chapter)),
        'combined_cjk':len(re.findall('[\u3400-\u9fff]',combined.decode())),
        'source_spans':sum('ref' in x for x in ITEMS), 'distinct_author_messages_used':len({x['ref'] for x in ITEMS if 'ref' in x}),
        'source_characters_selected':sum(x['source_span'][1]-x['source_span'][0] for x in ITEMS if 'ref' in x),
        'literal_retained_characters':sum(x.get('retained_characters',0) for x in ITEMS),
        'literal_retained_cjk':sum(x.get('retained_cjk',0) for x in ITEMS),
        'chapter_sha256':sha(data), 'combined_sha256':sha(combined),
        'boundary':'Literal overlap measures wording retention, not author approval of editorial additions.'}
    write_json(OUT/'editorial-statistics.json',metrics)
    ledger='# 原话与编辑对照\n\n[作者原话](00-author-original.md)保留所选会话消息，来源及原生时间见 selected-sources.json 与知识库对象。以下区间使用 Unicode 码点半开区间，全部修改可重放。章节中的解释与校正是编辑建议，不自动视为作者采纳。\n\n'
    for item in ITEMS:
        if item.get('reason')=='节标题':continue
        ledger+='## 段落单元 '+str(item['ordinal'])+'\n\n'
        if 'ref' in item:
            a,b=item['source_span']; ref=item['ref']
            ledger+=f'来源：{ref}，区间 [{a}, {b})。\n\n原话：\n\n'+SOURCES[ref]['text'][a:b]+'\n\n成文：\n\n'+item['text']+'\n\n'
        else:ledger+='编辑补写：'+item['reason']+'。\n\n'+item['text']+'\n\n'
    (OUT/'03-source-ledger.md').write_bytes(ledger.encode())
    print(json.dumps(metrics,ensure_ascii=False))

if __name__=='__main__':
    build()
