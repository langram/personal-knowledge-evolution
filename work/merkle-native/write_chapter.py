def source(ref, start=None, end=None, replacements=(), new=None):
    text = SOURCES[ref]['text']
    a = text.index(start) if start else 0
    b = text.index(end, a) + len(end) if end else len(text.rstrip())
    original = text[a:b]
    result = original if new is None else new.strip()
    for before, after in replacements:
        assert result.count(before) == 1, (ref, before)
        result = result.replace(before, after)
    operations = difflib.SequenceMatcher(None, original, result, autojunk=False).get_opcodes()
    ITEMS.append({'kind': 'source-exact' if original == result else 'source-adaptation',
        'ref': ref, 'text': result, 'source_span': [a, b], 'source_sha256': sha(original.encode()),
        'retained_characters': sum(j-i for tag,i,j,k,l in operations if tag == 'equal'),
        'retained_cjk': sum(len(re.findall('[\u3400-\u9fff]', original[i:j])) for tag,i,j,k,l in operations if tag == 'equal'),
        'edits': [{'operation': tag, 'source_span': [a+i,a+j], 'output_span': [k,l],
                   'before': original[i:j], 'after': result[k:l]} for tag,i,j,k,l in operations if tag != 'equal'],
        'author_assessment': '作者原话的摘取或润色；具体编辑改动供审阅，不预先视为作者采纳'})

